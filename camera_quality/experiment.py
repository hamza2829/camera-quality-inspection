def load_images(root, rows):
    images = [cv2.imread(str(root / row["image_path"]), cv2.IMREAD_GRAYSCALE) for row in rows]
    if any(image is None for image in images):
        raise OSError("Unreadable generated image")
    return images


def annotate(image, row, prediction, destination):
    canvas = cv2.cvtColor(cv2.resize(image, (384, 384), interpolation=cv2.INTER_NEAREST), cv2.COLOR_GRAY2BGR)
    x, y, width, height = [int(row[key])*4 for key in ("x", "y", "width", "height")]
    cv2.rectangle(canvas, (x, y), (x+width-1, y+height-1), (255, 255, 0), 2)
    for region in prediction["opencv"]["regions"]:
        x, y, width, height = [region[key]*4 for key in ("x", "y", "width", "height")]
        cv2.rectangle(canvas, (x, y), (x+width-1, y+height-1), (0, 0, 255), 2)
    canvas = cv2.copyMakeBorder(canvas, 65, 0, 0, 0, cv2.BORDER_CONSTANT, value=(20, 20, 20))
    title = f"{row['defect_type']} | CV:{prediction['opencv']['decision']} CNN:{prediction['cnn']['decision']}"
    cv2.putText(canvas, title, (8, 20), cv2.FONT_HERSHEY_SIMPLEX, .43, (255, 255, 255), 1, cv2.LINE_AA)
    cv2.putText(canvas, f"CNN defect probability: {prediction['cnn']['probability']:.3f}", (8, 39), cv2.FONT_HERSHEY_SIMPLEX, .43, (255, 255, 255), 1, cv2.LINE_AA)
    cv2.putText(canvas, "Cyan: truth | Red: OpenCV regions", (8, 57), cv2.FONT_HERSHEY_SIMPLEX, .43, (255, 255, 255), 1, cv2.LINE_AA)
    if not cv2.imwrite(str(destination), canvas):
        raise OSError("Failed to save annotated example")


